import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

export const THUMBS_DIR = path.join(ROOT, "public", "thumbs");
export const THUMBS_MODULE = path.join(ROOT, "src", "registry", "__generated__", "thumbs.ts");
export const INK_THUMBS_MODULE = path.join(ROOT, "src", "registry", "__generated__", "ink-thumbs.ts");
export const THUMB_THEMES = ["light", "dark"];
export const INK_THEME = "ink";

export const thumbPath = (slug, theme) => path.join(THUMBS_DIR, `${slug}.${theme}.webp`);

const hashes = new Map();

function fileHash(abs) {
  let stat;
  try {
    stat = fs.statSync(abs);
  } catch {
    return null;
  }
  const key = `${abs}:${stat.mtimeMs}:${stat.size}`;
  if (!hashes.has(key)) hashes.set(key, crypto.createHash("sha1").update(fs.readFileSync(abs)).digest("hex"));
  return hashes.get(key);
}

function thumbVersions(slugs) {
  const versions = {};
  for (const slug of [...new Set(slugs)].sort()) {
    const parts = THUMB_THEMES.map((theme) => fileHash(thumbPath(slug, theme)));
    if (parts.some((part) => part === null)) continue;
    versions[slug] = crypto.createHash("sha1").update(parts.join(":")).digest("hex").slice(0, 10);
  }
  return versions;
}

function inkVersions(slugs) {
  const versions = {};
  for (const slug of [...new Set(slugs)].sort()) {
    const hash = fileHash(thumbPath(slug, INK_THEME));
    if (hash) versions[slug] = hash.slice(0, 10);
  }
  return versions;
}

function thumbsModule(versions) {
  return `// Generated by scripts/thumbs.mjs and scripts/build-registry.mjs from public/thumbs. Do not edit.
export const thumbs: Record<string, string> = ${JSON.stringify(versions, null, 2)};
`;
}

function inkThumbsModule(versions) {
  return `// Generated by scripts/thumbs.mjs and scripts/build-registry.mjs from public/thumbs. Do not edit.
export const inkThumbs: Record<string, string> = ${JSON.stringify(versions, null, 2)};
`;
}

function writeModule(file, content) {
  try {
    if (fs.readFileSync(file, "utf8") === content) return false;
  } catch {}
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
  fs.writeFileSync(tmp, content);
  fs.renameSync(tmp, file);
  return true;
}

export function writeThumbsModule(slugs) {
  const versions = thumbVersions(slugs);
  const ink = inkVersions(slugs);
  const wroteThumbs = writeModule(THUMBS_MODULE, thumbsModule(versions));
  const wroteInk = writeModule(INK_THUMBS_MODULE, inkThumbsModule(ink));
  return { versions, ink, written: wroteThumbs || wroteInk };
}
