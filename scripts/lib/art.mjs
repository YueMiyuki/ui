import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

export const ART_DIR = path.join(ROOT, "public", "art");
export const ART_MODULE = path.join(ROOT, "src", "registry", "__generated__", "art.ts");

const FILE = /^([0-9a-f]{16})\.webp$/;

export const artPath = (hash) => path.join(ART_DIR, `${hash}.webp`);

export function artHashes() {
  let names = [];
  try {
    names = fs.readdirSync(ART_DIR);
  } catch {
    return [];
  }
  return names
    .map((name) => name.match(FILE)?.[1])
    .filter(Boolean)
    .sort();
}

function artModule(hashes) {
  return `// Generated by scripts/art.mjs and scripts/build-registry.mjs from public/art. Do not edit.
export const artFiles: ReadonlySet<string> = new Set<string>(${JSON.stringify(hashes, null, 1)});
`;
}

export function writeArtModule() {
  const hashes = artHashes();
  const content = artModule(hashes);
  try {
    if (fs.readFileSync(ART_MODULE, "utf8") === content) return { hashes, written: false };
  } catch {}
  fs.mkdirSync(path.dirname(ART_MODULE), { recursive: true });
  const tmp = `${ART_MODULE}.${process.pid}.${Date.now()}.tmp`;
  fs.writeFileSync(tmp, content);
  fs.renameSync(tmp, ART_MODULE);
  return { hashes, written: true };
}
